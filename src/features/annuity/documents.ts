import {
  accountHolder,
  annuitySummary,
  contract,
  documentCategories,
  incomeRider,
  indexStrategies,
  type AnnuityDocument
} from '@/constants/mock-api-annuity';
import { downloadPdf } from './download-pdf';
import { formatCurrency, formatPercent } from './utils';

const holderName = `${accountHolder.firstName} ${accountHolder.lastName}`;

function contractLines() {
  return [
    `Contract owner: ${holderName}`,
    `${accountHolder.addressLine1}, ${accountHolder.city}, ${accountHolder.state} ${accountHolder.zip}`,
    `Product: ${contract.productName} (${contract.contractType})`,
    `Contract number: ${contract.contractNumber}`,
    `Issue date: ${contract.issueDate}`
  ];
}

function fileNameFor(id: string) {
  return `${contract.contractNumber}-${id}.pdf`;
}

export function downloadAnnuityDocument(doc: AnnuityDocument) {
  downloadPdf(fileNameFor(doc.id), doc.title, [
    ...contractLines(),
    '',
    `Document type: ${documentCategories[doc.category].label}`,
    `Document date: ${doc.date}`,
    doc.description,
    '',
    'Sample document generated by the Annuity Portal demo.'
  ]);
}

export function downloadIncomeVerificationLetter() {
  downloadPdf(fileNameFor('income-verification'), 'Income verification letter', [
    `Date: ${contract.asOfDate}`,
    '',
    'To whom it may concern:',
    '',
    `This letter confirms that ${holderName} is the owner of ${contract.productName}`,
    `contract ${contract.contractNumber}, issued ${contract.issueDate}.`,
    '',
    `${holderName} receives guaranteed lifetime income under the ${incomeRider.name}`,
    `of ${formatCurrency(incomeRider.annualIncome)} per year, paid as ${formatCurrency(
      annuitySummary.guaranteedMonthlyIncome
    )} per month before taxes.`,
    `Payments began ${incomeRider.incomeStartDate} and continue for life. Coverage: ${incomeRider.coverage}.`,
    '',
    'Sample document generated by the Annuity Portal demo.'
  ]);
}

export function downloadAccountSummary() {
  downloadPdf(fileNameFor('account-summary'), `Account summary as of ${contract.asOfDate}`, [
    ...contractLines(),
    '',
    `Account value: ${formatCurrency(annuitySummary.accountValue)}`,
    `Surrender value: ${formatCurrency(annuitySummary.surrenderValue)}`,
    `Death benefit: ${formatCurrency(annuitySummary.deathBenefit)}`,
    `Income base: ${formatCurrency(incomeRider.incomeBase)}`,
    '',
    'Strategy allocation:',
    ...indexStrategies.map(
      (strategy) =>
        `  ${strategy.name}: ${strategy.allocationPercent}% (${formatCurrency(strategy.value)}), ${
          strategy.rateLabel
        } ${formatPercent(strategy.rate)}`
    ),
    '',
    'Sample document generated by the Annuity Portal demo.'
  ]);
}

export function downloadBeneficiaryChangeForm() {
  downloadPdf(fileNameFor('beneficiary-change-form'), 'Beneficiary change form', [
    ...contractLines(),
    '',
    'Primary beneficiaries (name, relationship, percentage):',
    '1. ______________________________________________',
    '2. ______________________________________________',
    '',
    'Contingent beneficiaries (name, relationship, percentage):',
    '1. ______________________________________________',
    '',
    'Owner signature: ____________________   Date: __________',
    '',
    'Sample document generated by the Annuity Portal demo.'
  ]);
}
