import {
  pensionPlan,
  type DepositAccount,
  type Participant,
  type PensionDocument
} from '@/constants/mock-api-pension';
import { downloadPdf } from '@/features/annuity/download-pdf';
import { formatCurrencyCents } from '@/features/annuity/utils';

function participantLines(participant: Participant) {
  return [
    `Participant: ${participant.firstName} ${participant.lastName}`,
    `${participant.addressLine1}, ${participant.city}, ${participant.state} ${participant.zip}`,
    `Plan: ${pensionPlan.planName}`,
    `Contract: ${pensionPlan.contractNumber}`
  ];
}

function fileNameFor(id: string) {
  return `contract-${pensionPlan.contractNumber}-${id}.pdf`;
}

export function downloadPensionDocument(doc: PensionDocument, participant: Participant) {
  downloadPdf(fileNameFor(doc.id), doc.title, [
    ...participantLines(participant),
    '',
    `Document date: ${doc.date}`,
    doc.description,
    '',
    'Sample document generated by the pension portal demo.'
  ]);
}

export function downloadWithholdingForm(kind: 'federal' | 'state', participant: Participant) {
  const title =
    kind === 'federal'
      ? 'Federal tax withholding (Form W-4P)'
      : `${participant.state} state tax withholding`;
  downloadPdf(fileNameFor(`${kind}-withholding`), title, [
    ...participantLines(participant),
    '',
    `Election on file as of ${pensionPlan.asOfDate}`,
    kind === 'federal' ? 'Filing status: Single' : `Withholding state: ${participant.state}`,
    'Withholding: none elected',
    '',
    'Sample document generated by the pension portal demo.'
  ]);
}

export function downloadPensionIncomeLetter(
  participant: Participant,
  accounts: DepositAccount[],
  grossMonthly: number
) {
  const name = `${participant.firstName} ${participant.lastName}`;
  downloadPdf(fileNameFor('income-verification'), 'Income verification letter', [
    `Date: ${pensionPlan.asOfDate}`,
    '',
    'To whom it may concern:',
    '',
    `This letter confirms that ${name} is a participant of the`,
    `${pensionPlan.planName} (contract ${pensionPlan.contractNumber}).`,
    '',
    `${name} receives a gross monthly pension payment of ${formatCurrencyCents(grossMonthly)},`,
    `paid by direct deposit to ${accounts.length} account(s) on the 15th of each month.`,
    '',
    'Sample document generated by the pension portal demo.'
  ]);
}
